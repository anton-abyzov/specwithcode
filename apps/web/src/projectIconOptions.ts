/** Emoji whose label matches every typed word. */
export function filterProjectEmojis(query: string): typeof PROJECT_EMOJIS {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return PROJECT_EMOJIS;
  return PROJECT_EMOJIS.filter((option) => {
    const text = `${option.label} ${option.keywords ?? ""}`.toLowerCase();
    return words.every((word) => text.includes(word));
  });
}

export function firstEmoji(value: string): string | null {
  const trimmed = value.trim();
  if (!trimmed) return null;
  const segments = new Intl.Segmenter(undefined, { granularity: "grapheme" }).segment(trimmed);
  const segment = segments[Symbol.iterator]().next().value?.segment;
  const isFlag = /^\p{Regional_Indicator}{2}$/u.test(segment ?? "");
  const isKeycap = /^[#*0-9]️?⃣$/u.test(segment ?? "");
  if (!segment || (!/\p{Extended_Pictographic}/u.test(segment) && !isFlag && !isKeycap)) {
    return null;
  }
  return segment;
}
