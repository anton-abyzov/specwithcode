const PROJECT_ICON_SEARCH_LIMIT = 300;
const choiceRank = new Map<string, number>(
  PROJECT_ICON_CHOICES.map((name, index) => [name, index]),
);

/** Icons for the picker: the curated set when empty, otherwise matches from every Lucide icon. */
export function filterProjectIconNames(query: string): ReadonlyArray<IconName> {
  const words = query
    .trim()
    .toLowerCase()
    .split(/[\s-]+/)
    .filter(Boolean);
  if (words.length === 0) return PROJECT_ICON_CHOICES;
  const keywordHits = new Set<string>(words.length === 1 ? (ICON_KEYWORDS[words[0]!] ?? []) : []);
  const joined = words.join("-");
  const score = (name: string) => {
    if (name === joined) return 0;
    if (name.startsWith(joined)) return 1;
    if (keywordHits.has(name)) return 2;
    return 3;
  };
  const rank = (name: string) => choiceRank.get(name) ?? Number.MAX_SAFE_INTEGER;
  return iconNames
    .filter((name) => keywordHits.has(name) || words.every((word) => name.includes(word)))
    .toSorted((a, b) => score(a) - score(b) || rank(a) - rank(b) || a.localeCompare(b))
    .slice(0, PROJECT_ICON_SEARCH_LIMIT);
}

