#!/usr/bin/env node
/**
 * Packages the extension two ways from the same files:
 *   - dist/specwithcode-browser-<version>.zip, the Chrome Web Store upload;
 *   - apps/server/src/browserExtension/extensionFiles.generated.ts, the copy
 *     the SpecWithCode service writes to disk for "Load unpacked".
 * `--check` fails when the generated copy is stale instead of writing it.
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeZlib from "node:zlib";
import * as NodeURL from "node:url";

const root = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "..");
const generatedPath = NodePath.resolve(
  root,
  "../server/src/browserExtension/extensionFiles.generated.ts",
);
const check = process.argv.includes("--check");

/** Store limits that rejected the earlier JobWeave upload when ignored. */
const LIMITS = { name: 75, short_name: 12, description: 132 };

export function packageFiles() {
  const files = ["manifest.json", "LICENSE", "NOTICE"];
  for (const dir of ["icons", "src"]) {
    for (const name of NodeFS.readdirSync(NodePath.join(root, dir)).sort()) {
      if (/\.(test|spec)\./.test(name)) continue;
      if (!/\.(js|html|css|png)$/.test(name)) continue;
      files.push(`${dir}/${name}`);
    }
  }
  return files;
}

export function validateManifest(manifest) {
  const problems = [];
  for (const [key, max] of Object.entries(LIMITS)) {
    const value = manifest[key];
    if (typeof value !== "string" || value.length === 0) problems.push(`${key} is missing`);
    else if (value.length > max)
      problems.push(`${key} is ${value.length} chars; the limit is ${max}`);
  }
  if (manifest.manifest_version !== 3) problems.push("manifest_version must be 3");
  if (!/^\d+\.\d+\.\d+$/.test(manifest.version ?? "")) problems.push("version must be x.y.z");
  if ("key" in manifest) problems.push("the store package must not carry a key");
  const allowed = new Set(["debugger", "tabs", "tabGroups", "storage", "alarms"]);
  for (const permission of manifest.permissions ?? [])
    if (!allowed.has(permission)) problems.push(`unreviewed permission: ${permission}`);
  if (manifest.host_permissions?.length) problems.push("host_permissions must stay empty");
  return problems;
}

/** A minimal ZIP writer (deflate, no data descriptors) so packaging needs no dependency. */
export function zip(entries) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  // 1980-01-01 keeps the archive byte-identical between builds.
  const dosTime = 0;
  const dosDate = (0 << 9) | (1 << 5) | 1;
  for (const { name, data } of entries) {
    const nameBytes = Buffer.from(name, "utf8");
    const compressed = NodeZlib.deflateRawSync(data, { level: 9 });
    const crc = NodeZlib.crc32(data) >>> 0;
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(8, 8);
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBytes, compressed);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(dosTime, 12);
    central.writeUInt16LE(dosDate, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(compressed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBytes.length, 28);
    central.writeUInt32LE((0o100644 << 16) >>> 0, 38);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBytes);
    offset += local.length + nameBytes.length + compressed.length;
  }
  const centralSize = centrals.reduce((sum, part) => sum + part.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, ...centrals, end]);
}

export function generatedModule(version, entries) {
  const lines = entries.map(
    ({ name, data }) =>
      `  { path: ${JSON.stringify(name)}, base64: ${JSON.stringify(data.toString("base64"))} },`,
  );
  return [
    "// Generated by apps/chrome-extension/scripts/build.mjs. Do not edit; run `pnpm --filter @specweave-studio/chrome-extension build`.",
    "/* eslint-disable */",
    `export const EXTENSION_VERSION = ${JSON.stringify(version)};`,
    "",
    "/** The unpacked SpecWithCode Browser extension, written to disk for Chrome's Load unpacked. */",
    "export const EXTENSION_FILES: ReadonlyArray<{ readonly path: string; readonly base64: string }> = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

function main() {
  const manifest = JSON.parse(NodeFS.readFileSync(NodePath.join(root, "manifest.json"), "utf8"));
  const problems = validateManifest(manifest);
  if (problems.length) {
    console.error(`manifest.json: ${problems.join("; ")}`);
    process.exit(1);
  }
  const entries = packageFiles().map((name) => ({
    name,
    data: NodeFS.readFileSync(NodePath.join(root, name)),
  }));
  const moduleText = generatedModule(manifest.version, entries);
  if (check) {
    const current = NodeFS.existsSync(generatedPath)
      ? NodeFS.readFileSync(generatedPath, "utf8")
      : "";
    if (current !== moduleText) {
      console.error(
        "extensionFiles.generated.ts is stale. Run `pnpm --filter @specweave-studio/chrome-extension build`.",
      );
      process.exit(1);
    }
    console.log(
      `extension ${manifest.version}: ${entries.length} files, generated copy is current`,
    );
    return;
  }
  NodeFS.mkdirSync(NodePath.join(root, "dist"), { recursive: true });
  const zipPath = NodePath.join(root, "dist", `specwithcode-browser-${manifest.version}.zip`);
  NodeFS.writeFileSync(zipPath, zip(entries));
  NodeFS.writeFileSync(generatedPath, moduleText);
  console.log(`wrote ${NodePath.relative(process.cwd(), zipPath)} (${entries.length} files)`);
  console.log(`wrote ${NodePath.relative(process.cwd(), generatedPath)}`);
}

if (process.argv[1] && NodePath.resolve(process.argv[1]) === NodeURL.fileURLToPath(import.meta.url))
  main();
